#!/usr/bin/env node
// Adapted from zool-theme/scripts/import-flag-icons.mjs (MIT, luoleiorg).
import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const expectedCommit = "fe15c16e7463d0c66d6c5730e9d0e832438d98e1"
const expectedLicenseHash = "8f1195d55a2fd315a07d812328470ca9ba2abb78c8d317ff19619d5125e00cea"
const expectedCountryHash = "f5e99aee5051868b391b9f42e110cb104b7fcd6269807b2dc5e2c80b1e6c9436"
const maximumSourceFlags = 300
const root = fileURLToPath(new URL("../", import.meta.url))
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex")

function assertSafeSvg(code, text) {
    const trimmed = text.trim()
    assert.ok(trimmed.startsWith("<svg") && trimmed.endsWith("</svg>"), `Malformed SVG for ${code}`)
    const stripped = trimmed
        .replaceAll('xmlns="http://www.w3.org/2000/svg"', "")
        .replaceAll('xmlns:xlink="http://www.w3.org/1999/xlink"', "")
    assert.ok(
        !/<script|<foreignObject|<iframe|<image|javascript:|https?:|on[a-z]+\s*=/i.test(stripped),
        `Unsafe SVG content in ${code}`,
    )
    for (const match of stripped.matchAll(/(?:xlink:)?href="([^"]*)"/g)) {
        assert.ok(match[1].startsWith("#"), `External href in ${code}: ${match[1]}`)
    }
}

function main() {
    assert.equal(
        process.argv.length,
        3,
        "Usage: node scripts/import-flag-icons.mjs /path/to/flag-icons",
    )
    const source = resolve(process.argv[2])
    const commit = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], {
        encoding: "utf8",
    }).trim()
    assert.equal(commit, expectedCommit, "flag-icons HEAD must match the pinned v7.3.2 commit")

    const license = readFileSync(join(source, "LICENSE"))
    const country = readFileSync(join(source, "country.json"))
    assert.equal(sha256(license), expectedLicenseHash, "LICENSE SHA256 mismatch")
    assert.equal(sha256(country), expectedCountryHash, "country.json SHA256 mismatch")

    const entries = JSON.parse(country.toString("utf8"))
    assert.ok(Array.isArray(entries), "country.json must contain an array")
    const isoEntries = entries.filter((entry) => entry.iso === true)
    assert.ok(isoEntries.length <= maximumSourceFlags, "ISO entry hard limit exceeded")
    assert.equal(isoEntries.length, 249, "Expected exactly 249 ISO entries")
    const isoCodes = isoEntries.map((entry) => entry.code)
    assert.ok(
        isoCodes.every((code) => typeof code === "string" && /^[a-z]{2}$/.test(code)),
        "Expected lowercase two-letter codes",
    )
    assert.equal(new Set(isoCodes).size, isoCodes.length, "Duplicate ISO codes")

    const codes = [...isoCodes].sort()
    assert.equal(codes.length, 249, "Expected exactly 249 imported flags")
    assert.ok(codes.includes("cn") && codes.includes("tw"), "Imported flag set check failed")

    // Read and validate all source assets before removing any previously generated SVGs.
    const assets = codes.map((code) => {
        const bytes = readFileSync(join(source, "flags", "4x3", `${code}.svg`))
        assert.ok(bytes.length > 0, `Empty SVG for ${code}`)
        assertSafeSvg(code, bytes.toString("utf8"))
        return { code, bytes }
    })
    const byFirst = new Map()
    for (const [first, second] of codes) {
        byFirst.set(first, (byFirst.get(first) ?? "") + second)
    }
    const packed = [...byFirst].map(([first, seconds]) => first + seconds).join(" ")
    const manifest = [
        "// Adapted from zool-theme/src/core/flags.manifest.ts (MIT, luoleiorg).",
        "// Generated by scripts/import-flag-icons.mjs; do not edit manually.",
        `// Source: https://github.com/lipis/flag-icons v7.3.2 (${expectedCommit}, MIT).`,
        "export const FLAG_CODES: ReadonlySet<string> = /* @__PURE__ */ new Set(",
        `    "${packed}"`,
        '        .split(" ")',
        "        .flatMap((group) => [...group.slice(1)].map((second) => group[0] + second)),",
        ")",
        "",
    ].join("\n")

    const destination = join(root, "public", "flags")
    mkdirSync(destination, { recursive: true })
    for (const name of readdirSync(destination)) {
        if (name.endsWith(".svg")) unlinkSync(join(destination, name))
    }
    for (const { code, bytes } of assets) {
        writeFileSync(join(destination, `${code}.svg`), bytes)
    }
    writeFileSync(join(destination, "LICENSE.txt"), license)
    mkdirSync(join(root, "src", "core"), { recursive: true })
    writeFileSync(join(root, "src", "core", "flags.manifest.ts"), manifest)

    const generated = readdirSync(destination)
        .filter((name) => name.endsWith(".svg"))
        .sort()
    assert.deepEqual(
        generated,
        codes.map((code) => `${code}.svg`),
        "Generated flag set mismatch",
    )
    assert.equal(generated.length, 249, "Expected exactly 249 generated SVGs")
    assert.ok(
        generated.includes("cn.svg") && generated.includes("tw.svg"),
        "Generated flag set check failed",
    )
    console.log("Imported 249 ISO 4:3 SVG flags from flag-icons v7.3.2.")
}

try {
    main()
} catch (error) {
    console.error(`Flag import failed: ${error instanceof Error ? error.message : String(error)}`)
    process.exitCode = 1
}
